#!/usr/bin/env python3
"""
ciel_schema_migrate.py — Migracja schematu Knowledge DB dla confidence/uncertainty.

Dodaje:
  - Kolumny confidence do doc_analysis
  - Tabelę confidence_scores (rozbicie na składowe)
  - Tabelę uncertainty_log (śledzenie niskiej pewności)
  - Tabelę source_reliability (wagi źródeł)

Uruchom: python3 scripts/ciel_schema_migrate.py [--db /tmp/noema_knowledge.db]
"""

import sqlite3
import json
import sys
import pathlib
import logging

logging.basicConfig(level=logging.INFO, format="[migrate] %(message)s")
log = logging.getLogger("migrate")

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "src"))
from ciel_geometry.paths import P

# Was hardcoded /tmp/noema_knowledge.db (tmpfs, wiped on reboot) — fixed 2026-07-08.
DEFAULT_DB = pathlib.Path(P.DB.KNOWLEDGE)


def migrate(conn: sqlite3.Connection) -> list[str]:
    """Run all migrations, return list of applied changes."""
    applied = []
    cur = conn.execute("SELECT name FROM sqlite_master WHERE type='table'")
    tables = {r[0] for r in cur.fetchall()}

    # 1. Add confidence columns to doc_analysis
    cur = conn.execute("PRAGMA table_info(doc_analysis)")
    doc_cols = {r[1] for r in cur.fetchall()}

    confidence_cols = {
        "confidence": "REAL DEFAULT 0.5",
        "source_type": "TEXT DEFAULT 'unknown'",
        "source_url": "TEXT DEFAULT ''",
        "source_reliability": "REAL DEFAULT 0.5",
        "cross_ref_count": "INTEGER DEFAULT 0",
        "recency_days": "INTEGER DEFAULT 9999",
        "consistency_score": "REAL DEFAULT 0.5",
        "is_uncertain": "INTEGER DEFAULT 1",
        "ingested_at": "TEXT DEFAULT ''",
    }

    for col_name, col_type in confidence_cols.items():
        if col_name not in doc_cols:
            conn.execute(f"ALTER TABLE doc_analysis ADD COLUMN {col_name} {col_type}")
            applied.append(f"doc_analysis.{col_name} ({col_type})")
            log.info(f"added doc_analysis.{col_name}")

    # 2. Create confidence_scores table
    if "confidence_scores" not in tables:
        conn.execute("""
            CREATE TABLE confidence_scores (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                doc_idx INTEGER,
                source_reliability REAL DEFAULT 0.5,
                cross_ref_score REAL DEFAULT 0.0,
                recency_score REAL DEFAULT 0.5,
                consistency_score REAL DEFAULT 0.5,
                self_consistency REAL DEFAULT 0.5,
                overall REAL DEFAULT 0.5,
                scored_at TEXT DEFAULT (datetime('now')),
                FOREIGN KEY (doc_idx) REFERENCES doc_analysis(idx)
            )
        """)
        applied.append("created table confidence_scores")
        log.info("created confidence_scores table")

    # 3. Create uncertainty_log table
    if "uncertainty_log" not in tables:
        conn.execute("""
            CREATE TABLE uncertainty_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                doc_idx INTEGER,
                confidence_score REAL,
                reason TEXT,
                details TEXT DEFAULT '',
                created_at TEXT DEFAULT (datetime('now')),
                resolved_at TEXT,
                resolution_note TEXT DEFAULT '',
                FOREIGN KEY (doc_idx) REFERENCES doc_analysis(idx)
            )
        """)
        applied.append("created table uncertainty_log")
        log.info("created uncertainty_log table")

    # 4. Create source_reliability weights table
    if "source_reliability" not in tables:
        conn.execute("""
            CREATE TABLE source_reliability (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                source_type TEXT UNIQUE,
                base_weight REAL,
                description TEXT,
                updated_at TEXT DEFAULT (datetime('now'))
            )
        """)
        # Seed default weights
        defaults = [
            ("academic_paper", 0.90, "Peer-reviewed paper or preprint"),
            ("government_edu", 0.85, ".gov or .edu domain"),
            ("technical_doc", 0.80, "Official documentation, specs"),
            ("news_reputable", 0.65, "Reuters, AP, BBC, Nature, Science"),
            ("news_general", 0.50, "General news outlet"),
            ("blog_technical", 0.55, "Technical blog, medium, substack"),
            ("blog_general", 0.35, "Personal blog, opinion piece"),
            ("llm_generated", 0.30, "Generated by another LLM"),
            ("user_provided", 0.50, "Information from user"),
            ("web_search", 0.40, "Unfiltered web search result"),
            ("cross_ref_derived", 0.60, "Inferred from multiple sources"),
            ("unknown", 0.40, "Unknown origin"),
        ]
        conn.executemany(
            "INSERT OR IGNORE INTO source_reliability (source_type, base_weight, description) VALUES (?, ?, ?)",
            defaults
        )
        applied.append("created table source_reliability with defaults")
        log.info("created source_reliability table with %d defaults", len(defaults))

    conn.commit()
    return applied


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Migrate Knowledge DB for confidence/uncertainty")
    parser.add_argument("--db", default=str(DEFAULT_DB), help="Path to knowledge.db")
    args = parser.parse_args()

    db_path = pathlib.Path(args.db)
    if not db_path.exists():
        log.error(f"DB not found at {db_path}")
        sys.exit(1)

    conn = sqlite3.connect(str(db_path), timeout=5)
    conn.execute("PRAGMA journal_mode=WAL")

    try:
        changes = migrate(conn)
        if changes:
            print(json.dumps({"migrations_applied": changes}, indent=2))
            log.info(f"Applied {len(changes)} migration(s)")
        else:
            log.info("Schema already up to date — no migrations needed")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
